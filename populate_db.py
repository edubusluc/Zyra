def _dt(value):
    return parse_datetime(value) if value else None


def _create(label, model, rows, build, keep_dates=()):
    """
    Crea las filas con bulk_create (sin pasar por save(): los datos ya vienen limpios)
    y devuelve {public_id: objeto}. Los campos auto_now_add se fijan después, porque
    bulk_create los rellena con la fecha actual.
    """
    objs = model.objects.bulk_create([build(row) for row in rows])
    for row in rows:
        dates = {f: _dt(row[f]) for f in keep_dates if row.get(f)}
        if dates:
            model.objects.filter(public_id=row["public_id"]).update(**dates)
    by_id = model.objects.in_bulk([o.public_id for o in objs], field_name="public_id")
    print(f"  {label}: {len(by_id)}")
    return by_id


def _ask(label, value, check):
    while True:
        value = (value or input(f"{label}: ")).strip()
        try:
            check(value)
            return value
        except ValidationError as exc:
            print(f"  {' '.join(exc.messages)}")
            value = ""


def _check_username(value):
    if not value:
        raise ValidationError("Escribe un nombre de usuario.")
    User.username_validator(value)


def ask_captain(args):
    """(usuario, email, contraseña o None) del capitán del club."""
    username = _ask("Usuario del capitán", args.usuario, _check_username)
    email = _ask("Email", args.email, validate_email).lower()
    if args.sin_contrasena:
        return username, email, None
    while True:
        password = getpass.getpass("Contraseña (vacía = sin contraseña, entra con Google): ")
        if not password:
            return username, email, None
        try:
            validate_password(password, User(username=username, email=email))
        except ValidationError as exc:
            print(f"  {' '.join(exc.messages)}")
            continue
        if getpass.getpass("Repítela: ") == password:
            return username, email, password
        print("  No coinciden, prueba otra vez.")


@transaction.atomic
def populate(username, email, password, superuser=False):
    captain = User(username=username, email=email, is_staff=superuser, is_superuser=superuser)
    if password:
        captain.set_password(password)
    else:
        captain.set_unusable_password()
    captain.save()
    # Email principal ya verificado (allauth): sin esto «Entrar con Google» no conecta con la cuenta.
    EmailAddress.objects.create(user=captain, email=email, verified=True, primary=True)
    print(f"  capitán: {captain.username} ({captain.email})" + (", también superusuario" if superuser else ""))

    clubs = _create("clubes", Club, CLUBS, lambda r: Club(public_id=r["public_id"], name=r["name"], slug=r["slug"]),
                    keep_dates=["created_at"])
    for club in clubs.values():
        Membership.objects.create(user=captain, club=club, role=Membership.ADMIN)
    teams = _create("equipos", Team, TEAMS, lambda r: Team(
        public_id=r["public_id"], club=clubs.get(r["club"]), is_own=r["is_own"], name=r["name"],
        in_group=r["in_group"], location=r["location"], photo=r["photo"]))
    players = _create("jugadores", Player, PLAYERS, lambda r: Player(
        public_id=r["public_id"], club=clubs.get(r["club"]), team=teams[r["team"]], name=r["name"],
        last_name=r["last_name"], position=r["position"], skillfull_hand=r["skillfull_hand"], photo=r["photo"],
        snp_score=r["snp_score"], in_team=r["in_team"], joined_season=r["joined_season"]))
    _create("histórico de puntos SNP", SnpScoreHistory, SNP_HISTORY, lambda r: SnpScoreHistory(
        public_id=r["public_id"], player=players[r["player"]], season=r["season"], date=parse_date(r["date"]),
        score=r["score"]))
    _create("completar equipo", SnpTeamImport, SNP_IMPORTS, lambda r: SnpTeamImport(
        public_id=r["public_id"], club=clubs[r["club"]], source=r["source"], status=r["status"],
        started_by=captain, finished_at=_dt(r["finished_at"]), to_add=r["to_add"],
        existing=r["existing"], created_players=r["created_players"], message=r["message"]),
        keep_dates=["created_at"])

    matches = _create("enfrentamientos", Match, MATCHES, lambda r: Match(
        public_id=r["public_id"], club=clubs.get(r["club"]), local=teams.get(r["local"]),
        visiting=teams.get(r["visiting"]), start_date=parse_date(r["start_date"]), result=r["result"],
        result_points=r["result_points"], draft_mode=r["draft_mode"], season=r["season"], location=r["location"]))
    games = _create("partidos", Game, GAMES, lambda r: Game(
        public_id=r["public_id"], match=matches[r["match"]], n_game=r["n_game"],
        player_1_local=players.get(r["player_1_local"]), player_2_local=players.get(r["player_2_local"]),
        player_1_visiting=players.get(r["player_1_visiting"]), player_2_visiting=players.get(r["player_2_visiting"]),
        score=r["score"], winner=r["winner"], draft_mode=r["draft_mode"]))
    _create("resultados", Result, RESULTS, lambda r: Result(
        public_id=r["public_id"], game=games[r["game"]], result=r["result"],
        set1_local=r["set1_local"], set1_visiting=r["set1_visiting"], set2_local=r["set2_local"],
        set2_visiting=r["set2_visiting"], set3_local=r["set3_local"], set3_visiting=r["set3_visiting"],
        draft_mode=r["draft_mode"]))

    calls = _create("convocatorias", Call, CALLS, lambda r: Call(public_id=r["public_id"], match=matches[r["match"]],
                                                                 draft_mode=r["draft_mode"]))
    Call.players.through.objects.bulk_create([
        Call.players.through(call=calls[r["public_id"]], player=players[p]) for r in CALLS for p in r["players"]
    ])
    _create("registros de convocatoria", CallLog, CALL_LOGS,
            lambda r: CallLog(public_id=r["public_id"], call=calls[r["call"]], text=r["text"]))
    _create("penalizaciones", Penalty, PENALTIES, lambda r: Penalty(
        public_id=r["public_id"], player=players[r["player"]], call=calls[r["call"]], reason=r["reason"]))


